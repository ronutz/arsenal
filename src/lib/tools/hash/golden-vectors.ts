/** How a vector's bytes are built (kept as recipes so a 1,000,000-byte input stays one line). */
export type ByteRecipe =
  // ASCII text, one byte per character (every character below U+0080).
  | { kind: "ascii"; text: string }
  // Bytes written as hexadecimal pairs.
  | { kind: "hex"; hex: string }
  // The values 0, 1, 2 ... count - 1 (count at most 256).
  | { kind: "range"; count: number }
  // One byte value repeated.
  | { kind: "repeat"; byte: number; count: number }
  // byte i = (i * mul + add) mod 256.
  | { kind: "pattern"; count: number; mul: number; add: number };

/**
 * materialise - the bytes a recipe describes. The fixture files the expected
 * digests were computed from were written by a separate Python generator with
 * the same recipes; a recipe that drifted from its file would fail every
 * digest of its vector.
 * @param recipe the recipe
 */
export function materialise(recipe: ByteRecipe): Uint8Array<ArrayBuffer> {
  // ASCII text: each character's code is the byte.
  if (recipe.kind === "ascii") {
    // One byte per character.
    const out = new Uint8Array(recipe.text.length);
    // Copy the codes (all below 0x80 by contract).
    for (let i = 0; i < recipe.text.length; i++) out[i] = recipe.text.charCodeAt(i);
    // Done.
    return out;
  }
  // Hexadecimal pairs.
  if (recipe.kind === "hex") {
    // Two characters per byte.
    const out = new Uint8Array(recipe.hex.length / 2);
    // Parse each pair.
    for (let i = 0; i < out.length; i++) out[i] = parseInt(recipe.hex.slice(i * 2, i * 2 + 2), 16);
    // Done.
    return out;
  }
  // 0, 1, 2 ... count - 1.
  if (recipe.kind === "range") {
    // The sequence.
    const out = new Uint8Array(recipe.count);
    // Each index is its own value.
    for (let i = 0; i < recipe.count; i++) out[i] = i;
    // Done.
    return out;
  }
  // One value repeated.
  if (recipe.kind === "repeat") return new Uint8Array(recipe.count).fill(recipe.byte);
  // The arithmetic pattern.
  const out = new Uint8Array(recipe.count);
  // byte i = (i * mul + add) mod 256.
  for (let i = 0; i < recipe.count; i++) out[i] = (i * recipe.mul + recipe.add) & 0xff;
  // Done.
  return out;
}

