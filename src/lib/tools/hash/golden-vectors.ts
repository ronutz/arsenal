/** How a blob vector's blob behaves. */
export type BlobSpec =
  // A real Blob holding these bytes.
  | { kind: "blob"; recipe: ByteRecipe }
  // A stand-in reporting this size whose read must never be called (a refusal must happen first).
  | { kind: "must-not-read"; size: number }
  // A stand-in whose read rejects with a DOMException of this name.
  | { kind: "read-rejects"; size: number; errorName: string }
  // A stand-in that reports one size and returns these bytes.
  | { kind: "short-read"; size: number; recipe: ByteRecipe }
  // A stand-in reporting 0 bytes whose read returns a detached (unusable) buffer, so hashing it throws.
  | { kind: "detached-buffer" };

