/** The order hashBytes runs the algorithms in, one after another (v2). */
export const STEP_ORDER_EXPECTED: readonly HashAlgorithm[] = ["SHA-256", "SHA-384", "SHA-512", "SHA-1"];

/** Field-by-field comparison of two digest records over every algorithm. */
function digestsMatch(got: Record<HashAlgorithm, HashDigest>, want: Record<HashAlgorithm, HashDigest>): string[] {
  // Collected differences.
  const errs: string[] = [];
  // Every algorithm, hex and base64.
  for (const a of HASH_ALGORITHMS) {
    // Hex as sha*sum prints it.
    if (got[a]?.hex !== want[a]?.hex) errs.push(`${a} hex ${got[a]?.hex}`);
    // Base64 as cksum --base64 prints it.
    if (got[a]?.base64 !== want[a]?.base64) errs.push(`${a} base64 ${got[a]?.base64}`);
  }
  // Empty when they agree.
  return errs;
}

/** The expected digests of a named byte fixture, without its byte count. */
function expectedDigests(name: string): Record<HashAlgorithm, HashDigest> {
  // The record coreutils produced.
  const e = BYTE_EXPECTED[name];
  // Only the four digests.
  return { "SHA-256": e["SHA-256"], "SHA-384": e["SHA-384"], "SHA-512": e["SHA-512"], "SHA-1": e["SHA-1"] };
}

/** Builds the blob a BlobSpec describes, with a counter of read calls. */
function buildBlob(spec: BlobSpec): { blob: ReadableBlob; reads: () => number } {
  // How many times arrayBuffer() was called.
  let reads = 0;
  // A real Blob holding the recipe's bytes.
  if (spec.kind === "blob") {
    // The platform Blob (Node 22 and every browser).
    const real = new Blob([materialise(spec.recipe)]);
    // Wrapped only to count the reads.
    return { blob: { size: real.size, arrayBuffer: () => { reads++; return real.arrayBuffer(); } }, reads: () => reads };
  }
  // A stand-in whose read must not happen.
  if (spec.kind === "must-not-read") return { blob: { size: spec.size, arrayBuffer: () => { reads++; return Promise.reject(new Error("read after a refusal")); } }, reads: () => reads };
  // A stand-in whose read fails like the File API's errors.
  if (spec.kind === "read-rejects") return { blob: { size: spec.size, arrayBuffer: () => { reads++; return Promise.reject(new DOMException("read failed", spec.errorName)); } }, reads: () => reads };
  // A stand-in whose buffer is detached (its byteLength reads 0) before it is handed back.
  if (spec.kind === "detached-buffer") return { blob: { size: 0, arrayBuffer: () => { reads++; const b = new ArrayBuffer(8); structuredClone(b, { transfer: [b] }); return Promise.resolve(b); } }, reads: () => reads };
  // A stand-in that reads fewer bytes than it reports.
  const bytes = materialise(spec.recipe);
  // Its own copy of the bytes, as arrayBuffer() returns.
  return { blob: { size: spec.size, arrayBuffer: () => { reads++; return Promise.resolve(bytes.slice().buffer); } }, reads: () => reads };
}

/** Same value, treating NaN as equal to NaN (JSON would turn NaN into null). */
function sameValue(a: unknown, b: unknown): boolean {
  // Object.is says NaN is NaN.
  if (typeof a === "number" && typeof b === "number") return Object.is(a, b);
  // Records: same keys, each the same value.
  if (a && b && typeof a === "object" && typeof b === "object") {
    // Both key lists.
    const ka = Object.keys(a as object), kb = Object.keys(b as object);
    // Same size, and every key agrees.
    return ka.length === kb.length && ka.every((k) => sameValue((a as Record<string, unknown>)[k], (b as Record<string, unknown>)[k]));
  }
  // Everything else by identity.
  return a === b;
}

/**
 * verifyVectors - run every v1 and v2 vector. ASYNC, because Web Crypto is.
 * Returns the { setId, total, passed, failures } shape the golden-vector
 * runner reads.
 */
export async function verifyVectors(): Promise<{ setId: string; total: number; passed: number; failures: string[] }> {
  // Every mismatch, one line each.
  const failures: string[] = [];
  // Counters.
  let total = 0;
  let passed = 0;
  // One vector's verdict.
  const record = (id: string, errs: string[]) => {
    // Counted.
    total++;
    // Pass or the reasons.
    if (errs.length === 0) passed++;
    else failures.push(`[${id}] ${errs.join("; ")}`);
  };

  // v1: the text vectors, unchanged.
  for (const v of HASH_GOLDEN_VECTORS) {
    // The text path.
    const r = await hashAll(v.input);
    // The input echoes, and every digest matches.
    record(`text:${v.name}`, [...(r.input === v.expected.input ? [] : ["input"]), ...digestsMatch(r.digests, v.expected.digests)]);
  }

  // v2: the byte fixtures against coreutils.
  for (const v of BYTE_GOLDEN_VECTORS) {
    // The bytes.
    const bytes = materialise(v.recipe);
    // The byte path.
    const r = await hashBytes(bytes);
    // What coreutils printed.
    const want = BYTE_EXPECTED[v.name];
    // A vector without expectations is itself a failure.
    if (!want) { record(`bytes:${v.name}`, ["no expected digests"]); continue; }
    // Length and every digest.
    record(`bytes:${v.name}`, [...(r.byteLength === want.byteLength && bytes.length === want.byteLength ? [] : [`length ${r.byteLength}/${want.byteLength}`]), ...digestsMatch(r.digests, expectedDigests(v.name))]);
  }

  // v2: the text and byte paths agree on the same bytes ("abc" typed, "abc" read).
  {
    // Typed.
    const t = await hashAll("abc");
    // Read. Copied into a fresh Uint8Array: the Worker's type check (tsconfig.worker.json) types TextEncoder.encode()
    // as Uint8Array<ArrayBufferLike>, and hashBytes takes bytes backed by an ordinary ArrayBuffer (2026-10-27).
    const b = await hashBytes(new Uint8Array(new TextEncoder().encode("abc")));
    // Identical digests.
    record("paths-agree:abc", digestsMatch(b.digests, t.digests));
  }

  // v2: the typed text "hi" and the file "hi" with a BOM and CRLF differ (a file is its bytes).
  {
    // Typed.
    const t = await hashAll("hi");
    // The file's digest, from coreutils.
    const f = expectedDigests("bom-crlf-hi");
    // Must not be equal.
    record("file-is-its-bytes:hi", t.digests["SHA-256"].hex === f["SHA-256"].hex ? ["typed and file digests unexpectedly equal"] : []);
  }

  // v2: the step order (one algorithm after another, SHA-256 first).
  {
    // The calls received.
    const seen: string[] = [];
    // A tiny input; the order is what matters.
    await hashBytes(new Uint8Array([1, 2, 3]), (a, i, n) => seen.push(`${a}:${i}/${n}`));
    // The expected calls.
    const want = STEP_ORDER_EXPECTED.map((a, i) => `${a}:${i}/${STEP_ORDER_EXPECTED.length}`);
    // Same sequence.
    record("step-order", JSON.stringify(seen) === JSON.stringify(want) ? [] : [`got ${JSON.stringify(seen)}`]);
  }

  // v2: the size decisions.
  for (const v of SIZE_DECISION_VECTORS) {
    // The decision.
    const d = v.limit === undefined ? decideFileSize(v.size) : decideFileSize(v.size, v.limit);
    // Field by field.
    record(`size:${v.name}`, sameValue(d, v.expected) ? [] : [`got ${JSON.stringify(d)}`]);
  }

  // v2: hashBlob, including refusals that must happen before any read.
  for (const v of BLOB_GOLDEN_VECTORS) {
    // The blob and its read counter.
    const { blob, reads } = buildBlob(v.blob);
    // The outcome.
    const out = await hashBlob(blob, v.limit === undefined ? {} : { limit: v.limit });
    // Collected differences.
    const errs: string[] = [];
    // A success is compared digest by digest with the named fixture.
    if (v.expect.ok) {
      // Must have succeeded.
      if (!out.ok) errs.push(`got ${JSON.stringify(out)}`);
      // Then the digests.
      else errs.push(...digestsMatch(out.result.digests, expectedDigests(v.expect.digestsOf)));
      // Exactly one read.
      if (reads() !== 1) errs.push(`reads ${reads()}`);
    } else {
      // A failure is compared field by field.
      if (!sameValue(out, v.expect)) errs.push(`got ${JSON.stringify(out)}`);
      // A refusal reads nothing; a read failure or short read reads once.
      const wantReads = v.expect.reason === "too-large" || v.expect.reason === "invalid-size" ? 0 : 1;
      // The read count.
      if (reads() !== wantReads) errs.push(`reads ${reads()}/${wantReads}`);
    }
    // The verdict.
    record(`blob:${v.name}`, errs);
  }

  // v2: the byte-size descriptions.
  for (const v of BYTE_SIZE_VECTORS) {
    // The description.
    const d = describeByteSize(v.bytes);
    // Field by field.
    record(`bytesize:${v.bytes}`, sameValue(d, v.expected) ? [] : [`got ${JSON.stringify(d)}`]);
  }

  // v2: the VirusTotal link.
  for (const v of VIRUSTOTAL_LINK_VECTORS) {
    // The URL, or null.
    const u = virusTotalFileReportUrl(v.input);
    // Exact.
    record(`virustotal:${v.name}`, u === v.expectedUrl ? [] : [`got ${u}`]);
  }

  // Catalogue check: every byte fixture has expectations and every expectation a fixture.
  {
    // The two name lists.
    const names = BYTE_GOLDEN_VECTORS.map((v) => v.name), keys = Object.keys(BYTE_EXPECTED);
    // Same set.
    record("catalogue:byte-fixtures", names.length === keys.length && names.every((n) => keys.includes(n)) ? [] : [`vectors ${names.join(",")} vs expected ${keys.join(",")}`]);
  }

  // The report.
  return { setId: GOLDEN_VECTOR_SET_ID, total, passed, failures };
}
