/** The Unicode version of the table. */
export const WIDTH_UNICODE_VERSION = "15.1.0"; // the version CPython 3.13 uses

/**
 * The number of terminal columns CPython gives one code point: 2 for W and F, otherwise 1.
 * @param cp a code point
 * @returns 1 or 2
 */
export function columnsOf(cp: number): 1 | 2 {
  if (cp < 0x1100) return 1; // nothing below U+1100 is wide (and ASCII never is)
  let lo = 0; // binary search over the sorted ranges
  let hi = WIDE.length - 1; // the last range
  while (lo <= hi) {
    const mid = (lo + hi) >> 1; // the middle range
    const [a, b] = WIDE[mid]; // its bounds
    if (cp < a) hi = mid - 1; // below it
    else if (cp > b) lo = mid + 1; // above it
    else return 2; // inside: wide
  } // while
  return 1; // in no range: narrow
} // columnsOf
