// character whose East_Asian_Width property is W (wide) or F (fullwidth) as
// two columns and every other character as one, and skips the lookup for an
// all-ASCII line (Lib/traceback.py of CPython 3.11, 3.12 and 3.13 as installed,
// and its rendering checked on 3.14.2). The ranges below are every code point
// listed as W or F in the Unicode Character Database 15.1.0 file
// EastAsianWidth.txt (read 2026-10-27), which is exactly the set CPython
// 3.13.16's unicodedata reports (unidata_version 15.1.0; compared code point by
// code point). CPython 3.14 uses Unicode 16.0.0, which lists 198 more code
// points as wide: 188 symbols that 16.0 reclassified (the trigrams, digrams and
// hexagrams at U+2630, U+268A and U+4DC0, the Tai Xuan Jing symbols at U+1D300
// and the counting rods at U+1D360) and 10 new characters; 3.15 uses 17.0.0,
// 355 more (the same 188 and 167 new). 3.12 uses 15.0.0 (5 fewer, all then
// unassigned). A marker under one of those characters can be off by a column
// on 3.14 or 3.15. Generated by make_widths.py; do not edit by hand.
// ============================================================================

